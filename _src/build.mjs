// Builds every page in _src/pages, the styles in _src/styles and the scripts in _src/scripts
// into the site root, plus sitemap.xml.
// Usage (from the repo root): node _src/build.mjs
//
// Each page file starts with a JSON front-matter block between two "---" lines,
// followed by the page body HTML. See _src/README.md for the fields.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { renderPage } from "./layout.mjs";
import { site } from "./config/site.mjs";
import { pendingScreenshots } from "./components/screenshot.mjs";

const srcDir = dirname(fileURLToPath(import.meta.url));
const rootDir = join(srcDir, "..");
const pagesDir = join(srcDir, "pages");
const stylesDir = join(srcDir, "styles");
const scriptsDir = join(srcDir, "scripts");

// Joined in this order into the one /style.css the pages load.
// Order matters: later files can override earlier ones, so responsive stays last.
const STYLE_FILES = [
  "tokens.css",
  "base.css",
  "layout.css",
  "buttons.css",
  "header.css",
  "hero.css",
  "screenshots.css",
  "cards.css",
  "content.css",
  "blog.css",
  "calculator.css",
  "faq.css",
  "footer.css",
  "marquee.css",
  "mobile-cta.css",
  "responsive.css",
];

function buildStyles() {
  const banner = `/* HUBNEX AI — generated from _src/styles by _src/build.mjs. Do not edit this file. */\n\n`;
  const css = STYLE_FILES.map((f) => readFileSync(join(stylesDir, f), "utf8")).join("\n");
  writeFileSync(join(rootDir, "style.css"), banner + css);
}

// Small progressive enhancements, joined into /site.js. The site works without them.
const SCRIPT_FILES = ["nav-dropdown.js", "copy-buttons.js", "faq-tabs.js", "calculator.js"];

function buildScripts() {
  const banner = `/* HUBNEX AI — generated from _src/scripts by _src/build.mjs. Do not edit this file. */\n`;
  const js = SCRIPT_FILES.map((f) => readFileSync(join(scriptsDir, f), "utf8")).join("\n");
  writeFileSync(join(rootDir, "site.js"), banner + js);
}

function listPages(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return listPages(path);
    return entry.name.endsWith(".html") ? [path] : [];
  });
}

function parsePage(file) {
  const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing "---" front matter`);
  try {
    return { ...JSON.parse(match[1]), body: match[2], source: relative(rootDir, file) };
  } catch (err) {
    throw new Error(`${file}: invalid front matter JSON (${err.message})`);
  }
}

function outputPath(url) {
  if (url.endsWith("/")) return join(rootDir, url, "index.html");
  return join(rootDir, url);
}

// Checks the on-page SEO rules from the plan and returns warnings.
function audit(page, html, knownUrls) {
  const warnings = [];
  const t = page.title.length;
  const d = page.description.length;
  if (t < 30 || t > 60) warnings.push(`title is ${t} chars (aim for 30-60)`);
  if (d < 120 || d > 160) warnings.push(`description is ${d} chars (aim for 120-160)`);
  if (page.type === "article" && !(page.category && page.published)) {
    warnings.push(`blog post needs "category" and "published" in its front matter`);
  }
  const h1s = html.match(/<h1[\s>]/g)?.length ?? 0;
  if (h1s !== 1) warnings.push(`has ${h1s} <h1> tags (need exactly 1)`);
  for (const [, src] of html.matchAll(/<img (?![^>]*\balt=)[^>]*src="([^"]+)"/g)) {
    warnings.push(`image without alt: ${src}`);
  }
  for (const [, href] of html.matchAll(/href="(\/[^"#]*)/g)) {
    const isPage = knownUrls.has(href);
    const isFile = existsSync(join(rootDir, href));
    if (!isPage && !isFile) warnings.push(`broken internal link: ${href}`);
  }
  return warnings;
}

buildStyles();
buildScripts();

const pages = listPages(pagesDir).map(parsePage);
const knownUrls = new Set(pages.map((p) => p.url));
const context = { posts: pages.filter((p) => p.type === "article") };
let warningCount = 0;

for (const page of pages) {
  const html = renderPage(page, context);
  const out = outputPath(page.url);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
  const warnings = audit(page, html, knownUrls);
  warningCount += warnings.length;
  console.log(`${warnings.length ? "!" : "✓"} ${page.url}`);
  for (const w of warnings) console.log(`    ${w}`);
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages
  .filter((p) => !p.noindex)
  .sort((a, b) => a.url.localeCompare(b.url))
  .map((p) => `  <url>\n    <loc>${site.origin}${p.url}</loc>\n    <lastmod>${p.updated}</lastmod>\n  </url>`)
  .join("\n")}
</urlset>
`;
writeFileSync(join(rootDir, "sitemap.xml"), sitemap);

console.log(`\nBuilt ${pages.length} pages, style.css, site.js and sitemap.xml with ${warningCount} warning(s).`);

const pending = pendingScreenshots();
if (pending.length) {
  console.log(`\nScreenshots still pending (${pending.length}), shown as placeholders on the site: ${pending.join(", ")}`);
}
if (warningCount) process.exitCode = 1;
